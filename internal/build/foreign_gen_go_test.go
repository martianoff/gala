// A GALA package may keep Go types in a .gen.go another generator wrote
// (oapi-codegen, stringer, protoc plugins). Such a file is source of its
// package like hand-written Go; only the GALA transpiler's own output, told by
// its header, is left out. These tests build programs that use such types.

// oapiGenGo is a Go file in the shape oapi-codegen writes.
func oapiGenGo(pkg, decls string) string {
	return "// Package " + pkg + " provides primitives to interact with the openapi HTTP API.\n" +
		"//\n" +
		"// Code generated by github.com/oapi-codegen/oapi-codegen/v2 version v2.4.1 DO NOT EDIT.\n" +
		"package " + pkg + "\n\n" + decls
}

// newForeignGenGoProject writes a module named moduleName holding files and
// isolates the user state and Go cache a build of it touches. It skips the
// test without a Go toolchain.
func newForeignGenGoProject(t *testing.T, moduleName string, files map[string]string) string {
	t.Helper()
	if _, err := exec.LookPath("go"); err != nil {
		t.Skip("go toolchain not on PATH")
	}
	projectDir := t.TempDir()
	files["gala.mod"] = "module " + moduleName + "\n\ngala 0.0.0\n"
	files["go.mod"] = "module " + moduleName + "\n\ngo 1.22\n"
	for name, content := range files {
		writeFixtureFile(t, filepath.Join(projectDir, filepath.FromSlash(name)), content)
	}
	isolateUserState(t)
	setEnvForTest(t, "GOCACHE", filepath.Join(t.TempDir(), "gocache"))
	alignGorootWithPathGo(t)
	return projectDir
}

// buildAndRun builds the project in projectDir from it and returns what the
// binary prints, its lines joined by "|". A toolchain that cannot build in
// this environment skips the test; a failed build fails it.
func buildAndRun(t *testing.T, projectDir string) string {
	t.Helper()
	return buildAndRunFrom(t, projectDir, "")
}

// buildAndRunFrom is buildAndRun for `gala build <sourceDir>`, a directory of
// the project; "" builds the project itself.
func buildAndRunFrom(t *testing.T, projectDir, sourceDir string) string {
	t.Helper()
	chdirForTest(t, projectDir)
	b, err := NewBuilder(projectDir, "test", false)
	require.NoError(t, err)
	if sourceDir != "" {
		b.SetSourceDir(sourceDir)
	}
	binPath, buildErr := b.Build("")
	if buildErr != nil {
		if isToolchainEnvError(buildErr.Error()) {
			t.Skipf("skipping end-to-end check: Go toolchain unavailable/mismatched in this environment: %v", buildErr)
		}
		t.Fatalf("gala build failed: %v", buildErr)
	}
	out, runErr := runBuiltBinary(binPath)
	require.NoError(t, runErr, "built binary failed to run; output:\n%s", out)
	return strings.Join(strings.Fields(out), "|")
}

// TestBuild_ForeignGenGo uses the types of a foreign .gen.go through a dot
// import, a qualified import, and from the package that holds it, in a library
// package and in package main. Each used to be GALA-E0023 (dot import) or an
// `undefined` from go build, which never got a copy of the file. A stale
// transpiler output beside it is still left out: it redeclares Describe.
func TestBuild_ForeignGenGo(t *testing.T) {
	projectDir := newForeignGenGoProject(t, "example.com/foreigngen", map[string]string{
		"lib/api.gen.go": oapiGenGo("lib", "type Pet struct {\n\tName string\n}\n"),
		// Same package: the library's own GALA code names the type.
		"lib/lib.gala": "package lib\n\nfunc Describe(p Pet) string = s\"pet ${p.Name}\"\n",
		"lib/stale.gen.go": genheader.Header + "\n\npackage lib\n\n" +
			"func Describe(p Pet) string { return \"stale\" }\n",
		// Qualified import.
		"shop/shop.gala": `package shop

import "example.com/foreigngen/lib"

func Tag(p lib.Pet) string = s"tag ${p.Name}"
`,
		// Same package, in package main, from a stringer-style generator.
		"kind_string.gen.go": "// Code generated by \"stringer -type=Kind\"; DO NOT EDIT.\n\npackage main\n\n" +
			"type Kind int\n\nfunc (k Kind) String() string { return \"kind\" }\n",
		// Dot import.
		"main.gala": `package main

import (
    . "example.com/foreigngen/lib"
    "example.com/foreigngen/shop"
)

func name(p Pet) string = p.Name

func label(k Kind) string = k.String()

func main() {
    Println(name(Pet(Name = "rex")))
    Println(Describe(Pet(Name = "tom")))
    Println(shop.Tag(Pet(Name = "ann")))
    Println(label(Kind(1)))
}
`,
	})

	assert.Equal(t, "rex|pet|tom|tag|ann|kind", buildAndRun(t, projectDir))
}

// foreignGenGoChildDir names the project a child process of
// TestBuild_ForeignGenGoEditReachesNextBuild builds.
const foreignGenGoChildDir = "GALA_TEST_FOREIGN_GEN_GO_DIR"

// TestBuild_ForeignGenGoEditReachesNextBuild edits only the foreign .gen.go
// between builds. Each build runs in a fresh process, as `gala build` does, so
// nothing but the on-disk caches carries over: the analysis cache must be keyed
// by the file, or the second build reports the type it added as undefined
// (and the third misses the one it removed).
func TestBuild_ForeignGenGoEditReachesNextBuild(t *testing.T) {
	const pet = "type Pet struct {\n\tName string\n}\n"
	projectDir := newForeignGenGoProject(t, "example.com/foreigngenedit", map[string]string{
		"lib/api.gen.go": oapiGenGo("lib", pet),
		"lib/lib.gala":   "package lib\n\nfunc Describe(p Pet) string = p.Name\n",
		"main.gala": `package main

import . "example.com/foreigngenedit/lib"

func owner(o Owner) string = o.Name

func main() {
    Println(Describe(Pet(Name = "rex")))
    Println(owner(Owner(Name = "ann")))
}
`,
	})

	build := func() string {
		cmd := exec.Command(os.Args[0], "-test.run=^TestBuild_ForeignGenGoChild$", "-test.v")
		cmd.Env = append(os.Environ(), foreignGenGoChildDir+"="+projectDir)
		out, _ := cmd.CombinedOutput()
		if strings.Contains(string(out), "SKIP: TestBuild_ForeignGenGoChild") || isToolchainEnvError(string(out)) {
			t.Skipf("child build skipped:\n%s", out)
		}
		return string(out)
	}
	api := filepath.Join(projectDir, "lib", "api.gen.go")

	require.Contains(t, build(), "undefined: Owner", "first build, before Owner exists")

	writeFixtureFile(t, api, oapiGenGo("lib", pet+"\ntype Owner struct {\n\tName string\n}\n"))
	require.Contains(t, build(), "OUTPUT<rex|ann>", "second build, after Owner was added")

	writeFixtureFile(t, api, oapiGenGo("lib", pet))
	require.Contains(t, build(), "undefined: Owner", "third build, after Owner was removed")
}

// TestBuild_ForeignGenGoChild is one build of
// TestBuild_ForeignGenGoEditReachesNextBuild, run in a process of its own.
func TestBuild_ForeignGenGoChild(t *testing.T) {
	projectDir := os.Getenv(foreignGenGoChildDir)
	if projectDir == "" {
		t.Skip("run by TestBuild_ForeignGenGoEditReachesNextBuild")
	}
	// The test binary's start-up points GOROOT at the Bazel SDK again; the
	// PATH `go` the build runs must find its own standard library.
	alignGorootWithPathGo(t)
	t.Logf("OUTPUT<%s>", buildAndRun(t, projectDir))
}

// x.gala is transpiled to x.gen.go, so another generator's x.gen.go beside it
// would be dropped from gen/ while the analyzer counts its types. The copy
// reports the collision instead.
func TestCopyNonGalaFiles_ForeignGenGoNamedLikeTranspilerOutput(t *testing.T) {
	for _, tc := range []struct{ gala, goFile string }{
		{"server.gala", "server.gen.go"},
		// A test source is transpiled to a _test.go name.
		{"server_test.gala", "server_test.gen_test.go"},
	} {
		t.Run(tc.gala, func(t *testing.T) {
			src := t.TempDir()
			writeFixtureFile(t, filepath.Join(src, "api", tc.gala), "package api\n")
			writeFixtureFile(t, filepath.Join(src, "api", tc.goFile), oapiGenGo("api", "type ServerInterface interface{}\n"))

			err := copyNonGalaFiles(src, t.TempDir(), false)
			require.Error(t, err)
			assert.Contains(t, err.Error(), tc.gala+" is transpiled to")
		})
	}
}
