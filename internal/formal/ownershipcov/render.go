package ownershipcov

import (
	"fmt"
	"sort"
	"strings"

	"martianoff/gala/internal/transpiler/ownership"
)

// counts is what one tree's reports add up to.
type counts struct {
	funcs, pointerFuncs, uniqueFuncs int
	bindings, unique                 int
	byRole                           map[ownership.Role][2]int // [all, unique]
	// reasons counts the bindings with at least one reason of each kind;
	// first is where the first such binding is.
	reasons map[ownership.ReasonKind]int
	first   map[ownership.ReasonKind]ownership.Reason
	// goSides counts the bindings that reach each Go function, method or
	// conversion, by the reason's detail.
	goSides map[string]int
}

func (t *Tree) count() counts {
	c := counts{byRole: map[ownership.Role][2]int{}, reasons: map[ownership.ReasonKind]int{},
		first: map[ownership.ReasonKind]ownership.Reason{}, goSides: map[string]int{}}
	for _, r := range t.Reports {
		for _, f := range r.Funcs {
			c.funcs++
			if len(f.Bindings) == 0 {
				continue
			}
			c.pointerFuncs++
			if f.Unique() {
				c.uniqueFuncs++
			}
			for _, b := range f.Bindings {
				c.bindings++
				role := c.byRole[b.Role]
				role[0]++
				if b.Unique {
					c.unique++
					role[1]++
				}
				c.byRole[b.Role] = role
				seen := map[ownership.ReasonKind]bool{}
				goSeen := map[string]bool{}
				for _, rs := range b.Reasons {
					if rs.Kind == ownership.PassedToGo && !goSeen[rs.Detail] {
						goSeen[rs.Detail] = true
						c.goSides[rs.Detail]++
					}
					if seen[rs.Kind] {
						continue
					}
					seen[rs.Kind] = true
					c.reasons[rs.Kind]++
					if _, ok := c.first[rs.Kind]; !ok {
						c.first[rs.Kind] = rs
					}
				}
			}
		}
	}
	return c
}

func pct(n, d int) string {
	if d == 0 {
		return "0.0%"
	}
	return fmt.Sprintf("%.1f%%", 100*float64(n)/float64(d))
}

// Render is the generated section of formal/COVERAGE.md for trees.
func Render(trees []*Tree) string {
	var b strings.Builder
	cs := make([]counts, len(trees))
	for i, t := range trees {
		cs[i] = t.count()
	}
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	w("## Ownership: why pointers are not unique\n\n")
	w("Generated by `bazel run //internal/formal/ownershipcov/update`; do not edit by hand.\n")
	w("It is the output of phase 1 of [the ownership design](../docs/OWNERSHIP_DESIGN.MD) (inferred\n")
	w("uniqueness, `internal/transpiler/ownership`) over the repository's GALA code. A pointer\n")
	w("binding (a `Ptr`/`*T` receiver or parameter, or a local `val` bound to a pointer) is\n")
	w("**unique** when it is of fresh origin, only ever lent downward, never reaches Go, and points\n")
	w("at an owned-shaped value. These are analysis results, not proofs.\n\n")

	w("| | ")
	for _, t := range trees {
		w("%s | ", t.Name)
	}
	w("\n|---|")
	for range trees {
		w("---|")
	}
	w("\n")
	row := func(label string, f func(c counts) string) {
		w("| %s | ", label)
		for _, c := range cs {
			w("%s | ", f(c))
		}
		w("\n")
	}
	row("Functions and methods", func(c counts) string { return fmt.Sprint(c.funcs) })
	row("…with a pointer binding", func(c counts) string { return fmt.Sprint(c.pointerFuncs) })
	row("…whose pointer bindings are all unique", func(c counts) string {
		return fmt.Sprintf("%d (%s)", c.uniqueFuncs, pct(c.uniqueFuncs, c.pointerFuncs))
	})
	row("Pointer bindings", func(c counts) string { return fmt.Sprint(c.bindings) })
	for _, role := range []ownership.Role{ownership.RoleReceiver, ownership.RoleParam, ownership.RoleLocal} {
		row("…"+string(role)+"s unique", func(c counts) string {
			r := c.byRole[role]
			return fmt.Sprintf("%d of %d", r[1], r[0])
		})
	}
	w("| Packages that did not analyze | ")
	for _, t := range trees {
		w("%d | ", len(t.Failed))
	}
	w("\n")

	w("\n### Reasons\n\n")
	w("Each binding that is not unique is counted once under every reason it has. The first\n")
	w("location is where the analysis first met the reason.\n\n")
	w("| Reason | Meaning |")
	for _, t := range trees {
		w(" %s |", t.Name)
	}
	w(" First location |\n|---|---|")
	for range trees {
		w("---|")
	}
	w("---|\n")
	for _, k := range ownership.Kinds {
		total := 0
		for _, c := range cs {
			total += c.reasons[k]
		}
		if total == 0 {
			continue
		}
		w("| `%s` | %s |", k, k.Describe())
		var first ownership.Reason
		for _, c := range cs {
			w(" %d |", c.reasons[k])
			if r, ok := c.first[k]; ok && first.File == "" {
				first = r
			}
		}
		w(" `%s:%d` |\n", first.File, first.Line)
	}

	w("\n### Where pointers reach Go\n\n")
	w("The Go functions, methods and conversions that `passed-to-go` bindings reach, by how many\n")
	w("bindings reach each (the 15 most frequent).\n\n")
	w("| Go side | Bindings |\n|---|---|\n")
	all := map[string]int{}
	for _, c := range cs {
		for k, n := range c.goSides {
			all[k] += n
		}
	}
	sides := make([]string, 0, len(all))
	for k := range all {
		sides = append(sides, k)
	}
	sort.Slice(sides, func(i, j int) bool {
		if all[sides[i]] != all[sides[j]] {
			return all[sides[i]] > all[sides[j]]
		}
		return sides[i] < sides[j]
	})
	if len(sides) > 15 {
		sides = sides[:15]
	}
	for _, s := range sides {
		w("| `passed-to-go:%s` | %d |\n", strings.ReplaceAll(s, "|", `\|`), all[s])
	}
	return b.String()
}
