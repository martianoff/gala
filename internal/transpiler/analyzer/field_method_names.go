package analyzer

import (
	"fmt"

	"martianoff/gala/galaerr"
	"martianoff/gala/internal/transpiler"
)

// goMethodNames returns the names of the methods hand-written .go files of
// the package being analyzed declare on its type meta.
func goMethodNames(richAST *transpiler.RichAST, meta *transpiler.TypeMetadata) map[string]bool {
	rec := richAST.GoTypeInfo.GetGalaTypeMethods(meta.Package + "." + meta.Name)
	if rec == nil {
		return nil
	}
	names := make(map[string]bool, len(rec.Methods))
	for name := range rec.Methods {
		names[name] = true
	}
	return names
}

// methodNames returns the name of every method type meta of the package being
// analyzed has in Go, but its Go case predicates: declared in any of its GALA
// files (a.currentOwnMethods), declared in a hand-written .go file of the
// package, or generated by the transformer.
func (a *galaAnalyzer) methodNames(richAST *transpiler.RichAST, meta *transpiler.TypeMetadata) map[string]bool {
	names := transpiler.GeneratedMethodNames(meta)
	for name := range a.currentOwnMethods[meta.Name] {
		names[name] = true
	}
	for name := range goMethodNames(richAST, meta) {
		names[name] = true
	}
	return names
}

// layoutSealedFields lays out the Go struct that holds every case of sealed
// type meta, from its cases: it names each case field in Go
// (SealedVariant.GoFieldNames) and fills the type's Fields, FieldNames and
// ImmutFlags with the struct's fields, ending with the case tag.
//
// A field keeps its own name unless the cases give it different types
// (fieldTypes holds the type texts each name is declared with) or methods has
// its name, as in `case Epsilon(Target int)` beside
// `func (t Transition) Target() int`. Such a field is stored once per case,
// as "Epsilon" + "Target", with "_" appended until the name is no case
// field's, method's or Go case predicate's. A field named like a Go case
// predicate keeps its name, and the predicate is left out. byRef marks the
// fields held through a pointer, which are not Immutable-wrapped.
func layoutSealedFields(meta *transpiler.TypeMetadata, fieldTypes map[string]map[string]bool, methods map[string]bool, byRef [][]bool) {
	taken := transpiler.SealedGoPredicateNames(meta)
	taken["_variant"] = true
	for name := range methods {
		taken[name] = true
	}
	for name := range fieldTypes {
		taken[name] = true
	}
	meta.Fields = make(map[string]transpiler.Type)
	meta.FieldNames, meta.ImmutFlags = nil, nil
	for vi := range meta.SealedVariants {
		v := &meta.SealedVariants[vi]
		v.GoFieldNames = make([]string, len(v.FieldNames))
		for fi, name := range v.FieldNames {
			goName := name
			if len(fieldTypes[name]) > 1 || methods[name] {
				goName = v.Name + name // e.g., "AddLeft", "SubLeft"
				for taken[goName] {
					goName += "_"
				}
				taken[goName] = true
			}
			v.GoFieldNames[fi] = goName
			if _, shared := meta.Fields[goName]; shared {
				continue
			}
			meta.Fields[goName] = v.FieldTypes[fi]
			meta.FieldNames = append(meta.FieldNames, goName)
			meta.ImmutFlags = append(meta.ImmutFlags, !byRef[vi][fi])
		}
	}
	meta.Fields["_variant"] = transpiler.BasicType{Name: "uint8"}
	meta.FieldNames = append(meta.FieldNames, "_variant")
	meta.ImmutFlags = append(meta.ImmutFlags, true)
}

// fieldNamedLikeMethodError rejects a struct of the package being analyzed
// with a field and a method of one name, which Go cannot hold. A method
// declared in filePath is reported at the method; a method declared in a
// hand-written .go file, or one the transformer generates (Copy, Equal,
// Unapply, Is<Type>), at the field of a struct declared in filePath. A struct
// field is read by its name, so unlike a sealed case field (see
// layoutSealedFields) it cannot be stored under another.
func (a *galaAnalyzer) fieldNamedLikeMethodError(richAST *transpiler.RichAST, pkgName, filePath string) error {
	var first *galaerr.SemanticError
	// DefinedIn may hold filePath spelled another way (absolute, canonical).
	isThisFile := func(p string) bool { return p == filePath || a.paths.sameFile(p, filePath) }
	// report keeps the clash nearest the top of filePath. A declaration
	// without a recorded position is reported at fallback (a position in
	// filePath) rather than left for `go build` to reject.
	report := func(pos, fallback transpiler.SourcePos, typeName, name string) {
		if pos.Line == 0 {
			pos = fallback
		}
		if first != nil && (first.Line < pos.Line || first.Line == pos.Line && first.Column <= pos.Column) {
			return
		}
		first = galaerr.NewCodedSemanticError(galaerr.CodeFieldNamedLikeMethod, pos.Line, pos.Column,
			fmt.Sprintf("type %s has both a field and a method named %s", typeName, name),
			"rename the field or the method; Go allows no field and method of one name on a type")
	}
	for _, meta := range richAST.Types {
		if meta.Package != pkgName || meta.IsSealed || meta.IsInterface || !a.currentOwnTypes[meta.Name] {
			continue
		}
		declaredHere := isThisFile(meta.DefinedIn)
		var other map[string]bool // methods declared outside GALA source
		for field := range meta.Fields {
			if a.currentOwnMethods[meta.Name][field] {
				if m := meta.Methods[field]; m != nil && isThisFile(m.DefinedIn) {
					report(m.Pos, transpiler.SourcePos{Line: 1, Column: 1}, meta.Name, field)
				}
				continue
			}
			if !declaredHere {
				continue
			}
			if other == nil {
				other = transpiler.GeneratedMethodNames(meta)
				for name := range goMethodNames(richAST, meta) {
					other[name] = true
				}
			}
			if other[field] {
				report(meta.FieldPositions[field], meta.Pos, meta.Name, field)
			}
		}
	}
	if first == nil {
		return nil
	}
	return first
}
