// collectDeclaredMethodNames records, by receiver type, the name of every
// method file sf declares. It reads the declarations alone, so a type's
// methods are known before any file of its package is analyzed.
func collectDeclaredMethodNames(sf *grammar.SourceFileContext, out map[string]map[string]bool) {
	for _, top := range sf.AllTopLevelDeclaration() {
		fd, ok := top.FunctionDeclaration().(*grammar.FunctionDeclarationContext)
		if !ok || fd.Receiver() == nil {
			continue
		}
		base := getBaseTypeName(fd.Receiver().(*grammar.ReceiverContext).Type_())
		if base == "" {
			continue
		}
		if out[base] == nil {
			out[base] = make(map[string]bool)
		}
		out[base][fd.Identifier().GetText()] = true
	}
}

// methodNames returns the name of every method type meta of the package being
// analyzed has in Go: declared in any of its GALA files, declared in a
// hand-written .go file of the package, or generated by the transformer.
func (a *galaAnalyzer) methodNames(richAST *transpiler.RichAST, meta *transpiler.TypeMetadata) map[string]bool {
	names := transpiler.GeneratedMethodNames(meta)
	for name := range a.currentOwnMethods[meta.Name] {
		names[name] = true
	}
	for name := range meta.Methods {
		names[name] = true
	}
	if rec := richAST.GoTypeInfo.GetGalaTypeMethods(meta.Package + "." + meta.Name); rec != nil {
		for name := range rec.Methods {
			names[name] = true
		}
	}
	return names
}

// layoutSealedFields lays out the Go struct that holds every case of sealed
// type meta, from its cases: it names each case field in Go
// (SealedVariant.GoFieldNames) and fills the type's Fields, FieldNames and
// ImmutFlags with the struct's fields, ending with the case tag. A field keeps
// its own name unless the cases give it different types (fieldTypes holds the
// type texts each name is declared with) or the type has a method of its name,
// as in `case Epsilon(Target int)` beside `func (t Transition) Target() int`:
// such a field is stored once per case, as "Epsilon" + "Target". byRef marks
// the fields held through a pointer, which are not Immutable-wrapped.
func layoutSealedFields(meta *transpiler.TypeMetadata, fieldTypes map[string]map[string]bool, methods map[string]bool, byRef [][]bool) {
	meta.Fields = make(map[string]transpiler.Type)
	meta.FieldNames, meta.ImmutFlags = nil, nil
	for vi := range meta.SealedVariants {
		v := &meta.SealedVariants[vi]
		v.GoFieldNames = make([]string, len(v.FieldNames))
		for fi, name := range v.FieldNames {
			goName := name
			if len(fieldTypes[name]) > 1 || methods[name] {
				goName = v.Name + name // e.g., "AddLeft", "SubLeft"
			}
			v.GoFieldNames[fi] = goName
			if _, shared := meta.Fields[goName]; shared {
				continue
			}
			meta.Fields[goName] = v.FieldTypes[fi]
			meta.FieldNames = append(meta.FieldNames, goName)
			meta.ImmutFlags = append(meta.ImmutFlags, !byRef[vi][fi])
		}
	}
	meta.Fields["_variant"] = transpiler.BasicType{Name: "uint8"}
	meta.FieldNames = append(meta.FieldNames, "_variant")
	meta.ImmutFlags = append(meta.ImmutFlags, true)
}

// fieldNamedLikeMethodError rejects a struct of the package being analyzed
// with a field and a method of one name, which Go cannot hold: a method
// declared in filePath, reported at the method, or one the transformer
// generates (Copy, Equal, Unapply, Is<Type>) on a struct declared in filePath,
// reported at the field. A struct field is read by its name, so unlike a
// sealed case field (see layoutSealedFields) it cannot be stored under another.
func (a *galaAnalyzer) fieldNamedLikeMethodError(richAST *transpiler.RichAST, pkgName, filePath string) error {
	var first *galaerr.SemanticError
	report := func(pos transpiler.SourcePos, typeName, name string) {
		if pos.Line == 0 || first != nil && (first.Line < pos.Line || first.Line == pos.Line && first.Column <= pos.Column) {
			return
		}
		first = galaerr.NewCodedSemanticError(galaerr.CodeFieldNamedLikeMethod, pos.Line, pos.Column,
			fmt.Sprintf("type %s has both a field and a method named %s", typeName, name),
			"rename the field or the method; Go allows no field and method of one name on a type")
	}
	for _, meta := range richAST.Types {
		if meta.Package != pkgName || meta.IsSealed || meta.IsInterface || !a.currentOwnTypes[meta.Name] {
			continue
		}
		var generated map[string]bool
		for field := range meta.Fields {
			if m := meta.Methods[field]; m != nil && m.DefinedIn == filePath {
				report(m.Pos, meta.Name, field)
				continue
			}
			if meta.DefinedIn != filePath {
				continue
			}
			if generated == nil {
				generated = transpiler.GeneratedMethodNames(meta)
			}
			if generated[field] && meta.Methods[field] == nil {
				report(meta.FieldPositions[field], meta.Name, field)
			}
		}
	}
	if first == nil {
		return nil
	}
	return first
}
