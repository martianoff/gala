#!/bin/sh
#
# Writes the Scoop manifest and the Homebrew formula for one GALA release,
# from that release's checksums-sha256.txt:
#
#   tools/install/render_packaging.sh VERSION CHECKSUMS SCOOP_OUT BREW_OUT
#
# release.yml runs it for every release and attaches the results as
# gala.json and gala.rb. bucket/gala.json and packaging/homebrew/gala.rb are
# this script's output for the release they name, which the installers
# workflow checks, so edit the templates here rather than those files.

set -eu

if [ $# -ne 4 ]; then
  echo "usage: $0 VERSION CHECKSUMS SCOOP_OUT BREW_OUT" >&2
  exit 2
fi
version="$1"
checksums="$2"
scoop_out="$3"
brew_out="$4"

base="https://github.com/martianoff/gala/releases/download"

hash_of() {
  h="$(awk -v name="$1" '$2 == name || $2 == "*" name { print $1; exit }' "$checksums")"
  if [ -z "$h" ]; then
    echo "$0: $checksums has no entry for $1" >&2
    exit 1
  fi
  printf '%s' "$h"
}

windows_amd64="$(hash_of gala-windows-amd64.exe)"
darwin_arm64="$(hash_of gala-darwin-arm64)"
darwin_amd64="$(hash_of gala-darwin-amd64)"
linux_arm64="$(hash_of gala-linux-arm64)"
linux_amd64="$(hash_of gala-linux-amd64)"

# The "#/gala.exe" suffix tells Scoop to save the download as gala.exe.
cat > "$scoop_out" <<EOF
{
    "version": "$version",
    "description": "GALA: a functional programming language that transpiles to Go",
    "homepage": "https://gala.fyi",
    "license": "Apache-2.0",
    "notes": "GALA compiles programs through Go 1.25+, which must be on your PATH (scoop install go).",
    "suggest": {
        "Go": "main/go"
    },
    "architecture": {
        "64bit": {
            "url": "$base/$version/gala-windows-amd64.exe#/gala.exe",
            "hash": "$windows_amd64"
        }
    },
    "bin": "gala.exe",
    "checkver": {
        "github": "https://github.com/martianoff/gala"
    },
    "autoupdate": {
        "architecture": {
            "64bit": {
                "url": "$base/\$version/gala-windows-amd64.exe#/gala.exe",
                "hash": {
                    "url": "\$baseurl/checksums-sha256.txt"
                }
            }
        }
    }
}
EOF

cat > "$brew_out" <<EOF
# Homebrew formula for GALA, generated by tools/install/render_packaging.sh
# from the release's checksums-sha256.txt. It belongs in a tap repository
# (martianoff/homebrew-gala, as Formula/gala.rb).
class Gala < Formula
  desc "Functional programming language that transpiles to Go"
  homepage "https://gala.fyi"
  version "$version"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$base/$version/gala-darwin-arm64"
      sha256 "$darwin_arm64"
    end
    on_intel do
      url "$base/$version/gala-darwin-amd64"
      sha256 "$darwin_amd64"
    end
  end

  on_linux do
    on_arm do
      url "$base/$version/gala-linux-arm64"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "$base/$version/gala-linux-amd64"
      sha256 "$linux_amd64"
    end
  end

  livecheck do
    url :stable
    strategy :github_latest
  end

  # GALA compiles programs through the Go toolchain.
  depends_on "go"

  def install
    bin.install Dir["gala-*"].first => "gala"
  end

  test do
    assert_match "GALA version #{version}", shell_output("#{bin}/gala version")
  end
end
EOF
